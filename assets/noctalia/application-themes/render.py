#!/usr/bin/python3
"""Render the recovered application CSS using Noctalia's semantic palette."""
import fcntl
import json
import math
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parent
STATE = Path.home() / '.local/state/noctalia/application-themes'
GTK = Path.home() / '.local/share/themes/Noctalia-LibreOffice/gtk-3.0'


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as f:
        f.write(text)
        temporary = Path(f.name)
    try:
        temporary.chmod(0o644)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def rgb(value):
    return [int(value[i:i+2], 16) for i in (1, 3, 5)]


def mix(a, b, amount):
    return '#' + ''.join(f'{math.floor(x*(1-amount)+y*amount+0.5):02x}'
                         for x, y in zip(rgb(a), rgb(b)))


def render(home=None):
    home = Path.home() if home is None else Path(home)
    palette = json.loads((STATE / 'palette.json').read_text())
    for key, value in palette.items():
        if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
            raise ValueError(f'Invalid color: {key}={value!r}')

    def replace(match):
        parts = match[1].split()
        if parts[0] == 'mix':
            return mix(palette[parts[1]], palette[parts[2]], float(parts[3].rstrip('%'))/100)
        key = parts[0]
        if key.endswith('_rgb'):
            return ','.join(map(str, rgb(palette[key[:-4]])))
        return palette[key]

    outputs = {}
    for app in ('firefox', 'zotero'):
        template = (ROOT / f'{app}.css.tpl').read_text()
        outputs[STATE / f'{app}.css'] = re.sub(r'\{\{\s*(.*?)\s*\}\}', replace, template)

    bg, fg, accent, selected, selected_fg, panel, base, muted = (
        palette[k] for k in ('background', 'foreground', 'accent', 'selection_background',
                             'selection_foreground', 'lighter_background', 'dark_background', 'muted'))
    # Both Noctalia variants have a dark/light surface with opposite text brightness.
    dark = sum(rgb(bg)) < sum(rgb(fg))
    # Omawrite watches this compatibility path and reloads colors automatically.
    omawrite = '# Generated by Noctalia application-themes/render.py; do not edit.\n'
    omawrite += f'mode = "{"dark" if dark else "light"}"\n'
    for key in ('background', 'foreground', 'accent', 'selection_background',
                'selection_foreground', 'lighter_background'):
        omawrite += f'{key} = "{palette[key]}"\n'
    outputs[home/'.local/state/omarchy/current/theme/colors.toml'] = omawrite
    resource = 'gtk-dark.css' if dark else 'gtk-contained.css'
    css = '/* Generated by noctalia/application-themes/render.py */\n'
    css += f'@import url("resource:///org/gtk/libgtk/theme/Adwaita/{resource}");\n'
    symbols = dict(theme_bg_color=bg, theme_fg_color=fg, theme_base_color=base,
                   theme_text_color=fg, theme_selected_bg_color=selected,
                   theme_selected_fg_color=selected_fg, insensitive_bg_color=bg,
                   insensitive_fg_color=muted, insensitive_base_color=base,
                   borders=palette['outline'], unfocused_borders=palette['outline_variant'], warning_color=palette['warning'],
                   error_color=palette['error'], success_color=palette['success'],
                   link_color=accent, visited_link_color=accent)
    for key, value in list(symbols.items()):
        if key.startswith('theme_'):
            symbols[key.replace('theme_', 'theme_unfocused_', 1)] = value
    css += ''.join(f'@define-color {key} {value};\n' for key, value in symbols.items())
    css += f'''
window, dialog, .background, .background:backdrop,
menubar, toolbar, .toolbar, statusbar, notebook, notebook > header,
menu, menuitem, popover, headerbar {{ background-color: {bg}; color: {fg}; }}
/* Override Adwaita's higher-specificity gray unfocused menu-bar background. */
menubar, .menubar, menubar:backdrop, .menubar:backdrop {{ background-color: {bg}; color: {fg}; }}
button, modelbutton, combobox button, spinbutton button {{
  background-image: none; background-color: {panel}; color: {fg}; border-color: {palette['outline']};
}}
button:hover, menuitem:hover, modelbutton:hover {{ background-color: {palette['hover']}; color: {palette['on_hover']}; }}
button:checked, button:active, menuitem:selected {{ background-image: none; background-color: {selected}; color: {selected_fg}; }}
entry, spinbutton, treeview, textview, textview text, .view {{ background-color: {base}; color: {fg}; }}
selection, *:selected {{ background-color: {selected}; color: {selected_fg}; }}
*:disabled {{ color: {muted}; }}
separator {{ background-color: {palette['outline_variant']}; }}
scrollbar {{ background-color: {bg}; }}
scrollbar slider {{ background-color: {muted}; }}
check:checked, radio:checked, scale highlight {{ background-color: {accent}; border-color: {accent}; color: {palette['on_accent']}; }}
tooltip, tooltip label {{ background-color: {panel}; color: {fg}; }}
'''
    outputs.update({GTK / name: css for name in ('gtk.css', 'gtk-dark.css')})
    # Qt's positional QPalette interface still comes from explicit desktop roles.
    qt = '[ColorScheme]\n'
    for state in ('active', 'inactive', 'disabled'):
        text = muted if state == 'disabled' else fg
        values = [text, panel, palette['hover'], panel, bg, palette['outline'], text,
                  fg, text, bg, bg, palette['shadow'], selected, selected_fg,
                  accent, palette['tertiary'], panel, bg, panel, fg, muted, accent]
        qt += f'{state}_colors=' + ', '.join(values) + '\n'
    for version in ('qt5ct', 'qt6ct'):
        outputs[home/'.config'/version/'colors/noctalia.conf'] = qt
    # Render and validate everything before publishing any of the outputs.
    for path, text in outputs.items():
        if '{{' in text:
            raise ValueError(f'Unresolved template in {path}')
    for path, text in outputs.items():
        atomic_write(path, text)


if __name__ == '__main__':
    # A GNOME default-mode launch must not regenerate the suspended Oma overrides.
    default_mode = Path.home() / '.config/oma-theme/vanilla.py'
    if default_mode.is_file():
        import runpy
        if runpy.run_path(str(default_mode))['active']():
            raise SystemExit(0)
    STATE.mkdir(parents=True, exist_ok=True)
    with (STATE / '.render.lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        render()
